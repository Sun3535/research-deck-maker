def _줄들(v) -> list[str]:
    """여러줄 칸 값 → 빈 줄 뺀 목록."""
    if isinstance(v, str):
        v = v.split("\n")
    return [str(x).strip() for x in (v or []) if str(x).strip()]


def _숫자들(v) -> list[tuple[str, str]]:
    """'값 | 설명' 줄들(또는 {"값","설명"}) → [(값, 설명)]."""
    out = []
    for x in (v if isinstance(v, list) else _줄들(v)):
        if isinstance(x, dict):
            out.append((str(x.get("값", "")), str(x.get("설명", ""))))
        elif str(x).strip():
            값, _, 설명 = str(x).partition("|")
            out.append((값.strip(), 설명.strip()))
    return out


