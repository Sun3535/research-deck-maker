def 사진격자(장: dict) -> list[박스]:
    b = _제목줄(장)
    그림들 = [g for g in (장.get("그림들") or []) if g][:6]
    라벨 = _줄들(장.get("라벨들"))
    n = max(len(그림들), 1)
    줄 = 1 if n <= 3 else 2
    칸 = -(-n // 줄)
    틈 = 32
    w = (폭 - 2 * 여백 - 틈 * (칸 - 1)) / 칸
    h = (690 - 틈 * (줄 - 1)) / 줄
    for i in range(n):
        x = 여백 + (i % 칸) * (w + 틈)
        y = 270 + (i // 칸) * (h + 틈)
        글 = 라벨[i] if i < len(라벨) else ""
        gh = h - (54 if 글 else 0)
        if i < len(그림들):     # 담기: 잘라 내지 않아 스케일바가 남는다
            b.append(박스("그림", x, y, w, gh, 자리=f"그림들.{i}", 그림=그림들[i], 맞춤="담기",
                         채움="면", 둥글기=12))
        else:
            b.append(박스("네모", x, y, w, gh, 채움="면", 둥글기=12))
        if 글:
            b.append(_글("라벨들", 글, x, y + gh + 8, w, 46, 스.글자["설명"], 700, 정렬="가운데"))
    return b


def 결론(장: dict) -> list[박스]:
    b = _제목줄(장)
