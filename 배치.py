    글상자 = _글("다음", 다음, x + 48, 390, cw - 96, 530, 스.글자["작은말"] - 2, 400)
    쓴높이 = 글높이(글상자.글, 글상자.w, 글상자.크기, 400, False) if 다음 else 0
    카드 = min(690, max(360, 120 + 쓴높이 + 72))       # 다음 단계가 짧으면 카드도 짧게
