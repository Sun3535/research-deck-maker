# ---------------------------------------------------------------- 글 재기
@lru_cache(maxsize=16)
def _글꼴(이름: str, 굵기: int) -> ImageFont.FreeTypeFont:
    _, 꼴 = 스.글자체(이름)
    for 파일 in 꼴["파일"][스.굵기맞춤(꼴, 굵기)]:
        if Path(파일).exists():
            return ImageFont.truetype(str(파일), 100)
    raise FileNotFoundError(f"글자체 파일이 없어요: {이름}")


def 글폭(글: str, 크기: float, 굵기: int = 400, 글자체: str | None = None) -> float:
    return _글꼴(글자체 or _지금글자체.get(), 굵기).getlength(글) * 크기 / 100


def 줄나누기(문단: str, 너비: float, 크기: float, 굵기: int = 400) -> list[str]:
    """띄어쓰기 단위로 줄을 나눈다(화면은 word-break: keep-all 과 같은 규칙)."""
    줄들, 지금 = [], ""
    for 낱말 in 문단.split(" "):
        후보 = f"{지금} {낱말}" if 지금 else 낱말
        if 글폭(후보, 크기, 굵기) <= 너비:
            지금 = 후보
            continue
        if 지금:
            줄들.append(지금)
        지금 = 낱말
        while 글폭(지금, 크기, 굵기) > 너비 and len(지금) > 1:  # 낱말 하나가 너무 길면 글자 단위로
            k = len(지금)
            while k > 1 and 글폭(지금[:k], 크기, 굵기) > 너비:
                k -= 1
            줄들.append(지금[:k])
            지금 = 지금[k:]
    if 지금 or not 줄들:
        줄들.append(지금)
    return 줄들


글머리 = "• "


def 글높이(문단들: list[str], 너비: float, 크기: float, 굵기: int, 점: bool) -> float:
    줄수 = 0
    for p in 문단들:
        안쪽 = 너비 - (글폭(글머리, 크기, 굵기) if 점 else 0)
        줄수 += len(줄나누기(p, 안쪽, 크기, 굵기))
    문단사이 = 0.45 * 크기 * max(0, len(문단들) - 1)
    return 줄수 * 크기 * 스.줄간격 + 문단사이


def 글맞추기(b: 박스, 가장작은: float | None = None) -> 박스:
    """글이 상자에 들어갈 때까지 글자를 줄인다. 가장 작은 크기에서도 넘치면 넘침 표시."""
    b.굵기 = 스.굵기맞춤(스.글자체(_지금글자체.get())[1], b.굵기)
    최소 = 가장작은 or 스.글자["가장작은"]
    크기 = b.크기
    while 크기 > 최소 and 글높이(b.글, b.w, 크기, b.굵기, b.점) > b.h:
        크기 -= 2
    b.크기 = max(크기, 최소)
    b.넘침 = 글높이(b.글, b.w, b.크기, b.굵기, b.점) > b.h + 1
    return b


