def 표(장: dict) -> list[박스]:
    b = _제목줄(장)
    t = 장.get("_표") or {"머리": [], "줄들": []}
    설명 = 장.get("설명")
    머리 = [str(v) if v is not None else "" for v in t["머리"]]
    n칸 = max([len(머리)] + [len(r) for r in t["줄들"]]) if 머리 or t["줄들"] else 0
    원줄들 = [(list(r) + [None] * n칸)[:n칸] for r in t["줄들"]]
    머리 = (머리 + [""] * n칸)[:n칸]
    칸글들, 정렬들 = _칸글들(원줄들, n칸)
    줄들 = [머리] + 칸글들
    줄수 = len(줄들)
    h = 690 - (60 if 설명 else 0)
    줄높이 = min(84, h / max(줄수, 1))
    w = 폭 - 2 * 여백
    크기 = max(스.글자["가장작은"], min(스.글자["본문"], 줄높이 * 0.45))
    넘침 = 줄높이 * 0.45 < 스.글자["가장작은"]

    def 필요너비(k):     # 칸마다 가장 긴 글 + 안쪽 여백(양쪽 18) + 여유
        return [max([글폭(줄[j], k, 700 if i == 0 else 400) for i, 줄 in enumerate(줄들)] + [0]) + 44
                for j in range(n칸)]
    필요 = 필요너비(크기)
    while sum(필요) > w and 크기 > 스.글자["가장작은"]:     # 안 들어가면 글자를 줄인다
        크기 = max(스.글자["가장작은"], 크기 - 1)
        필요 = 필요너비(크기)
    if n칸 and sum(필요) > w:
        넘침 = True
        너비들 = [w * x / sum(필요) for x in 필요]
    elif n칸:
        남음 = (w - sum(필요)) / n칸                         # 남는 너비는 고르게 나눠 준다
        너비들 = [x + 남음 for x in 필요]
    else:
        너비들 = []
    b.append(박스("표", 여백, 270, w, 줄높이 * 줄수, 자리="표", 크기=크기, 표=줄들,
                  칸너비들=너비들, 정렬들=정렬들, 넘침=넘침))
    if 설명:
        b.append(_글("설명", 설명, 여백, 270 + 줄높이 * 줄수 + 20, 폭 - 2 * 여백, 46,
                    스.글자["설명"], 400, "흐린글"))
    return b


def _소수자리(v: float) -> int:
    """값에 실제로 있는 소수 자리 수(최대 6). 10.0 → 0, 15.85 → 2, 0.00001 → 5."""
    if v != v or v in (float("inf"), float("-inf")) or v == int(v):
        return 0
    글 = f"{v:.6f}".rstrip("0")
    return len(글.split(".")[1]) if "." in 글 else 0


def _칸글들(줄들: list[list], n칸: int) -> tuple[list[list[str]], list[str]]:
    """표 칸 → 글. 숫자 칸은 열마다 소수 자리를 맞추고(지수 표기 없이) 오른쪽 정렬.
    값을 반올림해 바꾸지 않도록 열 안에서 가장 긴 소수 자리를 쓴다(최대 6자리)."""
    정렬들, 자리들 = [], []
    for j in range(n칸):
        값들 = [r[j] for r in 줄들 if r[j] not in (None, "")]
        숫자열 = bool(값들) and all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in 값들)
        정렬들.append("오른" if 숫자열 else "왼")
        자리들.append(max((_소수자리(float(v)) for v in 값들 if isinstance(v, float)), default=0)
                    if 숫자열 else None)
    글줄들 = []
    for r in 줄들:
        줄 = []
        for j, v in enumerate(r):
            if v is None:
                줄.append("")
            elif 자리들[j] is not None and isinstance(v, (int, float)) and not isinstance(v, bool):
                줄.append(f"{v:,.{자리들[j]}f}")
            else:
                줄.append(_칸글(v))
        글줄들.append(줄)
    return 글줄들, 정렬들


def _칸글(v) -> str:
    if v is None:
        return ""
    if isinstance(v, float):
        return f"{v:,.{_소수자리(v)}f}"
    return str(v)


