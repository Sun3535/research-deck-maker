def 수(v) -> float | None:
    """표 칸 값 → 숫자(못 바꾸면 None)."""
    if isinstance(v, bool) or v is None:
        return None
    if isinstance(v, (int, float)):
        return float(v)
    try:
        return float(str(v).replace(",", "").replace("%", "").strip())
    except ValueError:
        return None


def 도표자료(장: dict) -> dict:
    """장의 표(엔진이 _표 로 붙여 둔 것)에서 그릴 값을 고른다.

    가로: 첫 열(또는 장["가로"]), 세로: 숫자 열 전부(또는 장["세로"] 목록).
    """
    표 = 장.get("_표") or {"머리": [], "줄들": []}
    머리 = 표["머리"]
    if not 머리:
        return {}
    # 손으로 쓴 표는 줄 길이가 머리와 다를 수 있다 → 모자라면 빈칸으로 채운다
    줄들 = [(list(r) + [None] * len(머리))[:len(머리)] for r in 표["줄들"] if isinstance(r, (list, tuple))]
    가로열 = 머리.index(장["가로"]) if 장.get("가로") in 머리 else 0
    모양 = 장.get("모양") or "막대"
    if 모양 == "점":                 # 점 도표는 가로도 숫자여야 한다: 숫자가 아닌 줄은 뺀다
        줄들 = [r[:가로열] + [수(r[가로열])] + r[가로열 + 1:] for r in 줄들 if 수(r[가로열]) is not None]
    세로들 = [머리.index(c) for c in 장.get("세로", []) if c in 머리] or [
        i for i in range(len(머리)) if i != 가로열 and 줄들
        and all(수(r[i]) is not None for r in 줄들 if r[i] not in (None, ""))]
    return {"모양": 모양, "가로이름": 머리[가로열],
            "가로": [r[가로열] if 모양 == "점" else str(r[가로열]) for r in 줄들],
            "계열": [{"이름": 머리[i], "값": [수(r[i]) for r in 줄들]} for i in 세로들],
            "축0": 장.get("축0", 모양 == "막대"), "단위": 장.get("단위", "")}


