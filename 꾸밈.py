"""꾸밈: 배치가 끝난 박스 목록에 덱 전체 꾸밈을 입힌다. 기본은 전부 '없음'(꾸밈은 고를 때만).

설계의 "꾸밈": {"배경", "사진", "테두리", "그림자", "모서리"}
- 배경: 없음 / 구석빛 / 아래띠 / 점무늬     (장 맨 아래에 도형으로 깐다. PPTX에서도 도형)
- 사진: 없음 / 흑백 / 옅게                  (원본 그림은 그대로 두고 보이는 효과만. PPTX도 그림 효과)
- 테두리: 없음 / 얇게 / 강조                 (그림 둘레 선)
- 그림자: 없음 / 부드럽게                    (그림과 카드)
- 모서리: 그대로 / 둥글게 / 각지게           (그림과 카드의 모서리)
꽉 찬 바탕 장(사진가득, 끝, 반전 한마디, 그림배경·띠 표지)에는 배경 무늬를 깔지 않는다.
"""

from __future__ import annotations

from 배치 import 높이, 폭

고를것: dict[str, dict[str, str]] = {
    "배경": {"없음": "아무것도 깔지 않아요", "구석빛": "오른쪽 위에 강조색 빛", "아래띠": "아래에 가는 강조색 띠",
            "점무늬": "오른쪽 아래에 점 무늬"},
    "사진": {"없음": "원본 그대로", "흑백": "흑백으로 보이게(원본은 그대로)", "옅게": "조금 옅게(글을 돋보이게)"},
    "테두리": {"없음": "선 없음", "얇게": "그림 둘레에 가는 선", "강조": "강조색 굵은 선"},
    "그림자": {"없음": "그림자 없음", "부드럽게": "그림과 카드에 옅은 그림자"},
    "모서리": {"그대로": "장 틀대로", "둥글게": "그림·카드 모서리를 둥글게", "각지게": "모서리를 모두 각지게"},
}
기본 = {k: next(iter(v)) for k, v in 고를것.items()}


def _꽉찬바탕(박스들: list[dict]) -> bool:
    return any(b["x"] <= 0 and b["y"] <= 0 and b["w"] >= 폭 * 0.5 and b["h"] >= 높이 and
               b["종류"] in ("그림", "네모") and not b.get("투명") for b in 박스들[:2])


def _카드(b: dict) -> bool:
    return b["종류"] == "네모" and b["채움"] == "면" and b["w"] >= 200 and b["h"] >= 200


def _배경(무늬: str) -> list[dict]:
    def 네모(x, y, w, h, 채움, 투명=0.0, 모양=""):
        return {"종류": "네모", "x": x, "y": y, "w": w, "h": h, "자리": "", "글": [], "크기": 40, "굵기": 400,
                "색": "글", "정렬": "왼", "세로": "위", "점": False, "그림": "", "맞춤": "담기", "채움": 채움,
                "둥글기": 0, "넘침": False, "투명": 투명, "모양": 모양, "도표": {}, "표": [], "꾸밈": True}
    if 무늬 == "구석빛":
        return [네모(폭 - 520, -420, 980, 980, "강조", 0.9, "원"), 네모(폭 - 300, -260, 560, 560, "강조", 0.86, "원")]
    if 무늬 == "아래띠":
        return [네모(0, 높이 - 14, 폭, 14, "강조")]
    if 무늬 == "점무늬":
        return [네모(폭 - 60 - c * 36, 높이 - 60 - r * 36, 10, 10, "선", 0, "원")
                for r in range(5) for c in range(8) if r + c < 9]
    return []


def 입히기(박스들: list[dict], 꾸밈: dict | None) -> list[dict]:
    """박스 사전 목록 → 꾸민 목록(새 목록. 원래 것은 그대로)."""
    k = {**기본, **(꾸밈 or {})}
    if k == 기본:
        return 박스들
    out = []
    for b in 박스들:
        b = dict(b)
        큰그림 = b["종류"] == "그림" and not (b["w"] >= 폭 * 0.5 and b["h"] >= 높이)
        if b["종류"] == "그림" and k["사진"] != "없음" and b.get("자리") != "원본":
            b["필터"] = k["사진"]
        if 큰그림 and b.get("자리") != "원본":
            if k["테두리"] != "없음":
                b["테두리"], b["테두리폭"] = ("선", 3) if k["테두리"] == "얇게" else ("강조", 8)
            if k["그림자"] == "부드럽게":
                b["그림자"] = True
        if (큰그림 and b.get("자리") != "원본") or _카드(b):
            if k["모서리"] == "둥글게":
                b["둥글기"] = max(b["둥글기"], 28)
            elif k["모서리"] == "각지게":
                b["둥글기"] = 0
            if _카드(b) and k["그림자"] == "부드럽게":
                b["그림자"] = True
        out.append(b)
    if k["배경"] != "없음" and not _꽉찬바탕(박스들) and not any(b.get("자리") == "원본" for b in 박스들):
        out = _배경(k["배경"]) + out
    return out
